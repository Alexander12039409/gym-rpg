function xpToNext(level) {
  return Math.round(90 + level * 38 + Math.pow(level, 1.22) * 10);
}

function primaryProblem(problems) {
  const ids = problems || [];
  const order = ["beer", "puzo", "butt", "arms", "legs", "slouch", "chest", "neck"];
  const hit = order.find((id) => ids.includes(id));
  return PROBLEM_AVATAR[hit] || "beer";
}

function heroImg(user) {
  const g = user.gender === "f" ? "f" : "m";
  const lvl = user.level || 1;
  if (lvl < 8) {
    const z = PROBLEM_AVATAR[user.primaryProblem] || user.primaryProblem || "beer";
    const key = ["beer", "puzo", "butt", "arms", "legs", "slouch"].includes(z) ? z : "beer";
    return "assets/hero/" + g + "-start-" + key + ".png";
  }
  const stage = lvl >= 28 ? 3 : 2;
  const goal = user.goal || "gain";
  return "assets/hero/" + g + "-" + goal + "-" + stage + ".png";
}

function levelTitle(user) {
  const g = user.gender === "f" ? "f" : "m";
  const goal = user.goal || "gain";
  const list = (PATH_TITLES[g] && PATH_TITLES[g][goal]) || PATH_TITLES.m.gain;
  const i = Math.max(1, user.level || 1) - 1;
  if (i < list.length) return list[i];
  return list[list.length - 1] + " +" + (i - list.length + 1);
}

