function recommendedPacks(user) {
  const bt = (user && user.bodyType) || "average";
  const ex = (user && user.experience) || "newbie";
  return PROGRAM_PACKS
    .map((p) => {
      let s = 0;
      if ((p.forBody || []).indexOf(bt) >= 0) s += 2;
      if ((p.forExp || []).indexOf(ex) >= 0) s += 2;
      if (ex === "zero" && p.id === "full3") s += 2;
      if (ex === "zero" && p.id === "bodyweight") s += 2;
      return { p, s };
    })
    .sort((a, b) => b.s - a.s)
    .filter((x) => x.s > 0)
    .slice(0, 3)
    .map((x) => x.p);
}

